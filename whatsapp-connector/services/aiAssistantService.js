const PRIMARY_MODEL = process.env.GEMINI_MODEL || "gemini-flash-lite-latest";
const FALLBACK_MODEL = process.env.GEMINI_FALLBACK_MODEL || "gemini-flash-latest";
const DEFAULT_TEMPERATURE = parseFloat(process.env.GEMINI_TEMPERATURE || "0.2");
const DEFAULT_MAX_TOKENS = parseInt(process.env.GEMINI_MAX_TOKENS || "1200", 10);

function getGeminiApiKey() {
  const key = (process.env.GEMINI_API_KEY || "").trim();
  if (!key) {
    throw new Error(
      "GEMINI_API_KEY is not configured. Please set GEMINI_API_KEY in your backend .env file."
    );
  }
  return key;
}

